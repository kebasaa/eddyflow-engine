"""Every source is built, with the flags it always had, and nothing behind them.

This replaces test_makefile_deps_static.py. The Makefile it guarded had one
rule per object, generated by prj/gen_makefile_deps.py, because an object with
no rule was compiled once and never again: an edit landed, the object did not
change, and the previous compile was linked in its place with nothing said. It
happened to gas_slot_resolution.o and again to parse_month_grouping.o.

CMake reads every `use` and `include` itself, so there is no list left to
drift. What can still go wrong is which files are compiled and how:

- a source sitting outside the globbed folders is never built at all;
- a program unit inside them is linked into an executable that already has a
  main;
- CMake's own per-configuration flags (-O3, -DNDEBUG ...) creep in beside the
  engine's, or its Ninja generator runs cpp over the free-form sources, which
  defines `linux` and `unix` as 1 on those systems;
- fft4 picks up optimisation it was never compiled with.
"""

from pathlib import Path
import re
import unittest


ROOT = Path(__file__).resolve().parents[1]
CMAKELISTS = ROOT / "CMakeLists.txt"
BUILD = CMAKELISTS.read_text(encoding="utf-8").replace("\r\n", "\n")

#> The folders the build globs, as CMakeLists.txt spells them, and the
#> file pattern each takes.
GLOBBED = {
    "src/src_common": "*.f90",
    "src/src_rp": "*.f90",
    "src/src_rp/fft4": "*.F",
    "src/src_fcc": "*.f90",
    "src/src_os/win": "*.f90",
    "src/src_os/posix": "*.f90",
}
MAINS = {"src/src_rp/eddyflow-rp_main.f90", "src/src_fcc/eddyflow-fcc_main.f90"}
#> Kept out of the build on purpose: gitignored work in progress.
UNBUILT = ("src/src_common/deprecated", "src/src_common/under_development",
           "src/src_fcc/deprecated", "src/src_rp/deprecated")


def rel(path):
    return path.relative_to(ROOT).as_posix()


def program_units(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    return re.findall(r"(?im)^\s*program\s+\w+", text)


class EverySourceIsBuilt(unittest.TestCase):

    def test_each_folder_is_globbed(self):
        globs = {
            "src/src_common": '"${SRC}/src_common/*.f90"',
            "src/src_rp": '"${SRC}/src_rp/*.f90"',
            "src/src_rp/fft4": '"${SRC}/src_rp/fft4/*.F"',
            "src/src_fcc": '"${SRC}/src_fcc/*.f90"',
            "src/src_os/win": '"${SRC}/src_os/${OS_FAMILY}/*.f90"',
            "src/src_os/posix": '"${SRC}/src_os/${OS_FAMILY}/*.f90"',
        }
        for folder, glob in globs.items():
            self.assertIn(glob, BUILD, folder)
            self.assertIn("CONFIGURE_DEPENDS " + glob, BUILD, folder)

    def test_no_source_is_outside_them(self):
        stray = []
        for path in (ROOT / "src").rglob("*"):
            if path.suffix.lower() not in (".f90", ".f", ".for", ".f95", ".f03", ".f08"):
                continue
            where = rel(path)
            if where.startswith("src/src_tools/") or where.startswith(UNBUILT):
                continue
            folder = rel(path.parent)
            if folder not in GLOBBED or not path.match(GLOBBED[folder]):
                stray.append(where)
        self.assertEqual(stray, [], "these sources are not compiled into anything")


class EachExecutableHasOneMain(unittest.TestCase):

    def test_only_the_two_mains_are_programs(self):
        found = set()
        for folder, pattern in GLOBBED.items():
            for path in (ROOT / folder).glob(pattern):
                if program_units(path):
                    found.add(rel(path))
        self.assertEqual(found, MAINS)

    def test_the_mains_are_kept_out_of_the_shared_objects(self):
        self.assertIn('list(REMOVE_ITEM RP_SOURCES "${RP_MAIN}")', BUILD)
        self.assertIn('list(REMOVE_ITEM FCC_SOURCES "${FCC_MAIN}")', BUILD)

    def test_every_tool_is_a_fixture(self):
        for path in (ROOT / "src" / "src_tools").glob("*.f90"):
            self.assertTrue(program_units(path), path.name)
            self.assertRegex(BUILD, r"eddyflow_fixture\(\w+ \w+ %s\b" % re.escape(path.name),
                             path.name)


class TheFlagsAreTheEngines(unittest.TestCase):

    def test_cmakes_configuration_flags_are_cleared(self):
        self.assertIn("foreach(config DEBUG RELEASE RELWITHDEBINFO MINSIZEREL)\n"
                      '    set(CMAKE_Fortran_FLAGS_${config} "")', BUILD)

    def test_the_release_flags(self):
        flags = re.search(r"(?s)\nset\(EDDYFLOW_FFLAGS\b(.*?)\)", BUILD).group(1).split()
        for flag in ("-std=f2008", "-O3", "-ffp-contract=off", "-Wall", "-pedantic"):
            self.assertIn(flag, flags)
        for flag in ("-fbounds-check", "-fcheck=all", "-g"):
            self.assertNotIn(flag, flags, "a check flag is in the release build")

    def test_free_form_sources_are_not_preprocessed(self):
        fn = BUILD.split("function(eddyflow_fortran_target ")[1].split("endfunction()")[0]
        self.assertIn("Fortran_PREPROCESS OFF", fn)
        self.assertIn("target_compile_options(${target} PRIVATE ${EDDYFLOW_FFLAGS})", fn)

    def test_fft4_gets_no_optimisation(self):
        self.assertIn("target_compile_options(engine_fft4 PRIVATE -w)", BUILD)
        self.assertNotIn("eddyflow_fortran_target(engine_fft4)", BUILD)

    def test_the_fortran_runtime_is_linked_in(self):
        self.assertIn('set(EDDYFLOW_LDFLAGS "-shared-libgcc -static-libgfortran -static-libquadmath" CACHE STRING',
                      BUILD)
        self.assertIn("target_link_options(${target} PRIVATE ${EDDYFLOW_LDFLAGS_LIST})", BUILD)


class TheBinariesAreWhereEverythingLooks(unittest.TestCase):

    def test_bin_and_obj(self):
        self.assertIn('set(EDDYFLOW_BIN_DIR "${PROJECT_SOURCE_DIR}/bin/${OS_DIR}" CACHE PATH', BUILD)
        self.assertIn("eddyflow_executable(eddyflow_rp eddyflow_rp)", BUILD)
        self.assertIn("eddyflow_executable(eddyflow_fcc eddyflow_fcc)", BUILD)

    def test_no_makefile_is_left_to_drift(self):
        self.assertFalse((ROOT / "prj" / "Makefile").exists())
        self.assertFalse((ROOT / "prj" / "gen_makefile_deps.py").exists())


if __name__ == "__main__":
    unittest.main()
